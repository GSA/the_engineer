#!/usr/bin/env python3
"""Manual one-ticket Jira-to-Kata intake.

Retain an owner-supplied Jira XML export privately, record a human-approved
decomposition next to it, check that decomposition, and create the Kata tasks
with ticket traceability.

  init    parse one exported ticket into a private intake directory
  check   validate intake.toml against the retained source
  record  print (default) or run (--apply) the kata create commands
"""

import argparse
import datetime
import hashlib
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tomllib
import xml.etree.ElementTree as ET


REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DIR = REPO_ROOT / ".local" / "jira-intake"
KEY_RE = re.compile(r"^[A-Z][A-Z0-9_]+-[0-9]+$")


class IntakeError(Exception):
    pass


def sha256(data):
    return hashlib.sha256(data).hexdigest()


class _TextExtractor(HTMLParser):
    BLOCKS = {"p", "div", "br", "li", "ul", "ol", "tr", "h1", "h2", "h3", "h4", "h5", "h6"}

    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in self.BLOCKS:
            self.parts.append("\0")
        if tag == "li":
            self.parts.append("- ")

    def handle_endtag(self, tag):
        if tag in self.BLOCKS:
            self.parts.append("\0")

    def handle_data(self, data):
        self.parts.append(data)


def html_to_text(html):
    """Plain-text rendering of Jira's HTML; the HTML itself is retained too."""
    if not html:
        return ""
    parser = _TextExtractor()
    parser.feed(html)
    parser.close()
    blocks = (" ".join(block.split()) for block in "".join(parser.parts).split("\0"))
    return "\n\n".join(block for block in blocks if block)


def _text(element, path):
    found = element.find(path)
    return (found.text or "").strip() if found is not None else ""


def parse_export(data):
    """Return the ticket fields of a single-issue Jira RSS/XML export."""
    try:
        root = ET.fromstring(data)
    except ET.ParseError as exc:
        raise IntakeError(f"export is not valid XML: {exc}") from exc
    items = root.findall("./channel/item")
    if len(items) != 1:
        raise IntakeError(f"export must contain exactly one issue, found {len(items)}")
    item = items[0]
    key = _text(item, "key")
    if not KEY_RE.match(key):
        raise IntakeError(f"export has no valid issue key: {key!r}")
    custom = {}
    for field in item.findall("./customfields/customfield"):
        name = _text(field, "customfieldname")
        values = [(v.text or "").strip() for v in field.iter("customfieldvalue")]
        if name:
            custom[name] = values
    acceptance_html = None
    for name, values in custom.items():
        if name.strip().lower() == "acceptance criteria" and any(values):
            acceptance_html = "\n".join(values)
    generated = re.search(rb"RSS generated by JIRA[^\n]*", data)
    project = item.find("project")
    description_html = _text(item, "description")
    return {
        "key": key,
        "url": _text(item, "link"),
        "summary": _text(item, "summary"),
        "type": _text(item, "type"),
        "status": _text(item, "status"),
        "priority": _text(item, "priority"),
        "parent": _text(item, "parent") or None,
        "project": {
            "key": project.get("key") if project is not None else None,
            "name": (project.text or "").strip() if project is not None else None,
        },
        "created": _text(item, "created"),
        "updated": _text(item, "updated"),
        "site": _text(root, "./channel/link"),
        "export_generated": generated.group(0).decode().strip() if generated else None,
        "description_html": description_html,
        "description_text": html_to_text(description_html),
        "acceptance_criteria_html": acceptance_html,
        "acceptance_criteria_text": html_to_text(acceptance_html) if acceptance_html else None,
        "custom_fields": custom,
    }


def ensure_private(directory):
    """Refuse a destination that Git would track; restricted text stays private."""
    probe = directory
    while not probe.exists():
        probe = probe.parent
    result = subprocess.run(
        ["git", "-C", str(probe), "check-ignore", "-q", "--no-index", str(directory)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if result.returncode == 1:
        raise IntakeError(f"{directory} is inside a Git checkout and not ignored by Git")


def _toml_str(value):
    return json.dumps(value, ensure_ascii=False)


def _comment(text):
    return "\n".join(f"#   {line}" if line else "#" for line in text.splitlines())


def draft_toml(ticket, digest):
    original = ticket["acceptance_criteria_text"]
    if original:
        criteria = _comment(original)
    else:
        criteria = "#   (export has no Acceptance Criteria field; the description is the original requirement text)"
    return f"""\
# Manual Jira-to-Kata intake for {ticket['key']}.
# The original ticket is retained verbatim in source.xml and source.json.
# Edit only the sections below the [ticket] table, then run:
#   scripts/jira-intake.py check  <this file>
#   scripts/jira-intake.py record <this file> [--apply]

[ticket]
key = {_toml_str(ticket['key'])}
url = {_toml_str(ticket['url'])}
source_sha256 = {_toml_str(digest)}

# Original summary:
{_comment(ticket['summary'])}
# Original description:
{_comment(ticket['description_text'])}
# Original acceptance criteria:
{criteria}

# Owner-approved refinements (clarify the ticket; each needs approved_by/approved_at):
# [[refinement]]
# id = "R1"
# text = "..."
# approved_by = "owner"
# approved_at = "YYYY-MM-DD"

# Assumptions (recorded, not approved; carried into every task body):
# [[assumption]]
# id = "A1"
# text = "..."

# Open questions; a blocking question needs a resolution before recording:
# [[question]]
# id = "Q1"
# text = "..."
# blocking = true
# resolution = "..."

# Human-approved bounded Kata tasks, one per Kata project:
# [[task]]
# id = "T1"
# project = "kata-project-name"
# title = "..."
# outcome = "..."
# acceptance = ["..."]
# depends_on = []        # task ids that must finish first
# refinements = []       # refinement ids this task implements
# grounding = []         # Librarian qualified references, e.g. "D123#section"
# approved_by = "owner"
# approved_at = "YYYY-MM-DD"
"""


def _write_private(path, data):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(data)


def cmd_init(args):
    export = Path(args.export)
    data = export.read_bytes()
    ticket = parse_export(data)
    base = Path(args.dir).absolute()
    ensure_private(base)
    ticket_dir = base / ticket["key"]
    if ticket_dir.exists():
        raise IntakeError(f"{ticket_dir} already exists; edit its intake.toml instead")
    ticket_dir.mkdir(parents=True, mode=0o700)
    digest = sha256(data)
    source = {
        "schema": "engineer.jira-intake-source/v1",
        "ticket": ticket,
        "provenance": {
            "access_path": args.access_path,
            "export_file": export.name,
            "sha256": digest,
            "retained_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        },
    }
    _write_private(ticket_dir / "source.xml", data)
    _write_private(ticket_dir / "source.json", (json.dumps(source, indent=2, ensure_ascii=False) + "\n").encode())
    _write_private(ticket_dir / "intake.toml", draft_toml(ticket, digest).encode())
    print(f"{ticket['key']}: retained in {ticket_dir}")
    print(f"next: edit {ticket_dir / 'intake.toml'} with the approved decomposition")
    return 0


def _approved(entry):
    return [f"missing {field}" for field in ("approved_by", "approved_at") if not str(entry.get(field, "")).strip()]


def load_intake(path):
    """Return (intake, source, problems) for an intake.toml."""
    path = Path(path)
    intake = tomllib.loads(path.read_text())
    source = json.loads((path.parent / "source.json").read_text())
    problems = []
    ticket = intake.get("ticket", {})
    if ticket.get("key") != source["ticket"]["key"]:
        problems.append("ticket.key does not match source.json")
    xml_digest = sha256((path.parent / "source.xml").read_bytes())
    if xml_digest != source["provenance"]["sha256"] or ticket.get("source_sha256") != xml_digest:
        problems.append("source.xml no longer matches its recorded sha256")

    refinements = {}
    for entry in intake.get("refinement", []):
        rid = entry.get("id", "?")
        problems += [f"{rid}: {p}" for p in _approved(entry)]
        if not entry.get("text"):
            problems.append(f"{rid}: missing text")
        refinements[rid] = entry
    for entry in intake.get("question", []):
        if entry.get("blocking") and not str(entry.get("resolution", "")).strip():
            problems.append(f"{entry.get('id', '?')}: blocking question is unresolved")

    tasks = intake.get("task", [])
    if not tasks:
        problems.append("no tasks: record the human-approved decomposition in intake.toml")
    ids = [task.get("id") for task in tasks]
    if len(set(ids)) != len(ids):
        problems.append("task ids must be unique")
    for task in tasks:
        tid = task.get("id", "?")
        for field in ("project", "title", "outcome"):
            if not str(task.get(field, "")).strip():
                problems.append(f"{tid}: missing {field}")
        if not task.get("acceptance"):
            problems.append(f"{tid}: missing acceptance")
        problems += [f"{tid}: {p}" for p in _approved(task)]
        for dep in task.get("depends_on", []):
            if dep not in ids:
                problems.append(f"{tid}: unknown dependency {dep}")
        for ref in task.get("refinements", []):
            if ref not in refinements:
                problems.append(f"{tid}: {ref} is not an approved refinement")
    if not any("unknown dependency" in p for p in problems) and tasks:
        try:
            ordered(tasks)
        except IntakeError as exc:
            problems.append(str(exc))
    return intake, source, problems


def ordered(tasks):
    """Tasks in dependency order."""
    by_id = {task["id"]: task for task in tasks}
    done, result = set(), []
    while len(result) < len(tasks):
        ready = [t for t in tasks if t["id"] not in done and set(t.get("depends_on", [])) <= done]
        if not ready:
            raise IntakeError("dependency cycle among tasks: " + ", ".join(sorted(set(by_id) - done)))
        for task in ready:
            done.add(task["id"])
            result.append(task)
    return result


def cmd_check(args):
    intake, _, problems = load_intake(args.intake)
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1
    print(f"{intake['ticket']['key']}: {len(intake['task'])} approved tasks ready to record")
    return 0


def task_body(task, intake, source):
    ticket = source["ticket"]
    refinements = {r["id"]: r for r in intake.get("refinement", [])}
    lines = [
        "## Outcome",
        task["outcome"],
        "",
        "## Acceptance criteria",
        *[f"- {item}" for item in task["acceptance"]],
        "",
        "## Source ticket",
        f"- Jira: {ticket['key']} {ticket['url']}",
        f"- Summary: {ticket['summary']}",
        f"- Provenance: {source['provenance']['access_path']}, sha256 {source['provenance']['sha256']}",
        f"- Intake task: {task['id']}, approved by {task['approved_by']} on {task['approved_at']}",
        "",
        "### Original description",
        ticket["description_text"] or "(empty)",
        "",
        "### Original acceptance criteria",
        ticket["acceptance_criteria_text"] or "(none in export)",
    ]
    if task.get("refinements"):
        lines += ["", "## Approved refinements"]
        lines += [
            f"- {rid}: {refinements[rid]['text']} ({refinements[rid]['approved_by']}, {refinements[rid]['approved_at']})"
            for rid in task["refinements"]
        ]
    if intake.get("assumption"):
        lines += ["", "## Assumptions (unapproved)"]
        lines += [f"- {a['id']}: {a['text']}" for a in intake["assumption"]]
    if task.get("grounding"):
        lines += ["", "## Librarian grounding", *[f"- {ref}" for ref in task["grounding"]]]
    return "\n".join(lines) + "\n"


def create_args(task, intake, source, recorded):
    key = source["ticket"]["key"]
    args = [
        "kata", "create", task["title"],
        "--project", task["project"],
        "--body", task_body(task, intake, source),
        "--idempotency-key", f"jira-{key}-{task['id']}",
        "--meta", f"jira.key={key}",
        "--meta", f"jira.url={source['ticket']['url']}",
        "--meta", f"jira.source_sha256={source['provenance']['sha256']}",
        "--meta", f"jira.intake_task={task['id']}",
    ]
    if "priority" in task:
        args += ["--priority", str(task["priority"])]
    for dep in task.get("depends_on", []):
        args += ["--blocked-by", recorded.get(dep, f"<{dep}>")]
    return args + ["--json"]


def cmd_record(args):
    path = Path(args.intake)
    intake, source, problems = load_intake(path)
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1
    log_path = path.parent / "recorded.json"
    log = json.loads(log_path.read_text()) if log_path.exists() else {"tasks": {}}
    recorded = log["tasks"]
    for task in ordered(intake["task"]):
        if task["id"] in recorded:
            print(f"{task['id']}: already recorded as {recorded[task['id']]}")
            continue
        argv = create_args(task, intake, source, recorded)
        if not args.apply:
            print(shlex.join(argv))
            continue
        result = subprocess.run(argv, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        if result.returncode != 0:
            print(f"error: {task['id']}: kata create failed: {result.stderr.strip()}", file=sys.stderr)
            return 1
        short_id = json.loads(result.stdout)["issue"]["short_id"]
        recorded[task["id"]] = f"{task['project']}#{short_id}"
        log_path.write_text(json.dumps({"ticket": source["ticket"]["key"], "tasks": recorded}, indent=2) + "\n")
        print(f"{task['id']}: created {recorded[task['id']]}")
    if not args.apply:
        print("# dry run: rerun with --apply to create these tasks", file=sys.stderr)
    return 0


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="retain one exported ticket privately and draft intake.toml")
    init.add_argument("export", help="single-issue Jira XML export")
    init.add_argument("--access-path", required=True, help="how the export was obtained, e.g. 'owner-supplied XML export'")
    init.add_argument("--dir", default=str(DEFAULT_DIR), help=f"private intake root (default {DEFAULT_DIR})")
    init.set_defaults(func=cmd_init)
    check = sub.add_parser("check", help="validate an intake.toml")
    check.add_argument("intake")
    check.set_defaults(func=cmd_check)
    record = sub.add_parser("record", help="print or run the kata create commands")
    record.add_argument("intake")
    record.add_argument("--apply", action="store_true", help="create the tasks in Kata")
    record.set_defaults(func=cmd_record)
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except (IntakeError, OSError, tomllib.TOMLDecodeError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
