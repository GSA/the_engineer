def _load_local_env():
    spec = importlib.util.spec_from_file_location("local_env", LOCAL_ENV_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _node_executable() -> str:
    local_env = _load_local_env()
    try:
        node_bin = local_env.node_bin_dir()
        candidate = node_bin / "node"
        if candidate.is_file():
            return str(candidate)
    except Exception:
        pass
    return "node"


def _probe_forge_extension(surface: str) -> dict:
    """Run the real forge-workspace.ts extension against a synthetic base or Forge worktree cwd."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "repo"
        worktree = root / ".local" / "environment" / "forge" / "worktrees" / "github" / "org" / "repo" / "ws1"
        worktree.mkdir(parents=True, exist_ok=True)
        root_agents = root / "AGENTS.md"
        wt_agents = worktree / "AGENTS.md"
        wt_override = worktree / "AGENTS.override.md"
        root_agents.write_text("# Root instructions\n", encoding="utf-8")
        wt_agents.write_text("# Worktree instructions\n", encoding="utf-8")
        wt_override.write_text(
            "<!-- generated by kenn-forge; safe to delete; regenerated on agent launch -->\n"
            "# Kenn Forge Workspace Context\n- Workspace ID: ws1\n\n# Working agreements\n- Worktree instructions\n",
            encoding="utf-8",
        )
        cwd = worktree if surface == "forge_workspace" else root
        context_files = (
            [
                {"path": str(root_agents), "content": "# Root instructions\n"},
                {"path": str(wt_agents), "content": "# Worktree instructions\n"},
            ]
            if surface == "forge_workspace"
            else [{"path": str(root_agents), "content": "# Root instructions\n"}]
        )
        script = textwrap.dedent(
            f"""
            import forgeWorkspaceExtension from {json.dumps(str(FORGE_EXTENSION_PATH))};
            delete process.env.KENN_FORGE_RUNTIME_SESSION_KEY;
            delete process.env.KENN_FORGE_API_URL;
            delete process.env.PI_SUBAGENT_EXTENSION_BINDINGS;
            const handlers = new Map();
            forgeWorkspaceExtension({{
              on(event, handler) {{
                const list = handlers.get(event) ?? [];
                list.push(handler);
                handlers.set(event, list);
              }},
            }});
            const ctx = {{ cwd: {json.dumps(str(cwd))}, sessionManager: {{ getSessionId: () => "syn-1" }} }};
            const beforeEvent = {{
              type: "before_agent_start",
              systemPromptOptions: {{
                contextFiles: {json.dumps(context_files)},
                sections: {{}},
              }},
            }};
            for (const h of handlers.get("before_agent_start") ?? []) {{
              await h(beforeEvent, ctx);
            }}
            const readEvent = {{
              type: "tool_result",
              toolName: "read",
              isError: false,
              input: {{ path: "/opt/superpowers/skills/writing-plans/SKILL.md" }},
              content: [{{ type: "text", text: "# Writing Plans" }}],
            }};
            let readResult;
            for (const h of handlers.get("tool_result") ?? []) {{
              const next = await h(readEvent, ctx);
              if (next) readResult = next;
            }}
            const paths = beforeEvent.systemPromptOptions.contextFiles.map((f) => f.path);
            console.log(JSON.stringify({{
              forge_section: Boolean(beforeEvent.systemPromptOptions.sections.forge_workspace),
              ancestor_agents_filtered: !paths.includes({json.dumps(str(root_agents))}),
              override_replaces_worktree_agents:
                paths.includes({json.dumps(str(wt_override))}) && !paths.includes({json.dumps(str(wt_agents))}),
              skill_overrides_active: Boolean(
                readResult?.content?.some((c) => c.text?.includes("Kenn Forge Workspace Override (Active)"))
              ),
            }}));
            """
        )
        proc = subprocess.run(
            [_node_executable(), "--input-type=module", "-e", script],
            check=True,
            text=True,
            capture_output=True,
        )
        return json.loads(proc.stdout.strip())


def evaluate_prompt_surface(
    surface: str,
    *,
    cwd: Path | None = None,
    coding_model: str = "claude-opus-5.5",
    review_model: str = "gemini-4-argon",
) -> dict:
    if surface == "private_pi":
        probe = _probe_forge_extension("private_pi")
        return {
            "allowed": (
                not probe["forge_section"]
                and not probe["skill_overrides_active"]
            ),
            "surface": "private_pi",
            "forge_workspace_section_injected": probe["forge_section"],
            "ancestor_agents_filtered": False,
            "override_replaces_worktree_agents": False,
            "skill_overrides_active": probe["skill_overrides_active"],
            "requires_owner_approval_for_push": True,
            "requires_human_merge": True,
        }
    if surface == "forge_workspace":
        probe = _probe_forge_extension("forge_workspace")
        return {
            "allowed": (
                probe["forge_section"]
                and probe["ancestor_agents_filtered"]
                and probe["override_replaces_worktree_agents"]
                and probe["skill_overrides_active"]
            ),
            "surface": "forge_workspace",
            "forge_workspace_section_injected": probe["forge_section"],
            "ancestor_agents_filtered": probe["ancestor_agents_filtered"],
            "override_replaces_worktree_agents": probe["override_replaces_worktree_agents"],
            "skill_overrides_active": probe["skill_overrides_active"],
            "requires_owner_approval_for_push": False,
            "requires_human_merge": True,
        }
    if surface == "roborev_review":
        local_env = _load_local_env()
        try:
            coding_norm, review_norm = local_env.validate_paired_models(coding_model, review_model)
            coding_family = local_env.usai_model_family(coding_norm)
            review_family = local_env.usai_model_family(review_norm)
        except Exception as exc:
            return {
                "allowed": False,
                "surface": "roborev_review",
                "reason": str(exc),
                "required_flags": ["--no-mcp", "--no-skills"],
                "read_only": True,
                "forge_workspace_section_injected": False,
            }
        return {
            "allowed": True,
            "surface": "roborev_review",
            "required_flags": ["--no-mcp", "--no-skills"],
            "read_only_tools": ["read", "grep", "find", "ls", "json_output"],
            "read_only": True,
            "coding_family": coding_family,
            "review_family": review_family,
            "forge_workspace_section_injected": False,
            "requires_human_merge": True,
        }
    raise GateError(f"Unknown prompt surface: {surface!r}")


def _is_temporary_plan_path(rel_path: str) -> bool:
    normalized = rel_path.replace("\\", "/").lstrip("./")
    return any(normalized.startswith(prefix) for prefix in TEMPORARY_PLAN_PREFIXES)


def _git_changed_paths(repo_root: Path, *diff_args: str) -> list[str]:
    proc = subprocess.run(
        ["git", "-C", str(repo_root), "diff", "--name-status", *diff_args],
        check=False,
        text=True,
        capture_output=True,
    )
    if proc.returncode != 0:
        return []
    paths = []
    for raw_line in proc.stdout.splitlines():
        parts = raw_line.strip().split("\t")
        if len(parts) < 2:
            continue
        status = parts[0].strip()
        if status.startswith("D"):
            continue
        target_path = parts[-1].strip()
        paths.append(target_path)
    return paths


def check_temporary_plans(repo_root: Path, *, base_ref: str = "main") -> dict:
    repo_root = Path(repo_root).resolve()
    staged_violations = sorted(
        path for path in _git_changed_paths(repo_root, "--cached") if _is_temporary_plan_path(path)
    )
    branch_violations = sorted(
        path for path in _git_changed_paths(repo_root, f"{base_ref}...HEAD") if _is_temporary_plan_path(path)
    )
    working_violations = []
    for prefix in TEMPORARY_PLAN_PREFIXES:
        directory = repo_root / prefix.rstrip("/")
        if directory.is_dir():
            for file_path in sorted(directory.rglob("*")):
                if file_path.is_file() or file_path.is_symlink():
                    working_violations.append(file_path.relative_to(repo_root).as_posix())
    all_violations = sorted(set(staged_violations) | set(branch_violations) | set(working_violations))
    return {
        "allowed": not all_violations,
        "staged_violations": staged_violations,
        "branch_violations": branch_violations,
        "working_violations": working_violations,
        "violations": all_violations,
    }


def evaluate_publication_gate(
    action: str,
    *,
    surface: str,
    branch: str = "kenn-forge/kata/mpew",
    commit_sha: str = "",
    reviewed_commits: list[str] | tuple[str, ...] = (),
    findings: list[dict] | tuple[dict, ...] = (),
    plans_clean: bool = True,
    targets_registered: bool = False,
    owner_approved: bool = False,
    human_operator: bool = False,
) -> dict:
    if surface == "roborev_review":
        return {
            "allowed": False,
            "action": action,
            "surface": surface,
            "reason": "roborev_review is read-only and cannot commit, push, create PRs, or merge",
        }
    if surface not in ("private_pi", "forge_workspace"):
        raise GateError(f"Unknown surface: {surface!r}")

    if action == "amend":
        if commit_sha and commit_sha in set(reviewed_commits) and not owner_approved:
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": f"Commit {commit_sha} was already reviewed; make an additive fix commit instead of amending",
            }
        if not owner_approved and surface == "private_pi":
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": "Amending commits in private_pi requires explicit owner approval",
            }
        return {"allowed": True, "action": action, "surface": surface, "reason": "amend allowed"}

    if not plans_clean:
        return {
            "allowed": False,
            "action": action,
            "surface": surface,
            "reason": "Temporary working plans/specs must be removed before commit or publication",
        }

    if action == "commit":
        return {"allowed": True, "action": action, "surface": surface, "reason": "local commit allowed"}

    # Evaluate review findings before any push/PR/merge action
    for finding in findings:
        fid = finding.get("id", "unknown")
        in_scope = bool(finding.get("in_scope"))
        confirmed = bool(finding.get("confirmed"))
        disposition = str(finding.get("disposition", "")).strip()
        if in_scope and confirmed:
            if disposition != "fixed" or not str(finding.get("fix_commit", "")).strip():
                return {
                    "allowed": False,
                    "action": action,
                    "surface": surface,
                    "reason": f"Confirmed in-scope finding {fid} must be fixed by an additive commit before publication",
                }
        elif disposition in ("skipped_invalid", "escalated_out_of_scope"):
            if not str(finding.get("evidence", "")).strip():
                return {
                    "allowed": False,
                    "action": action,
                    "surface": surface,
                    "reason": f"Skipped or out-of-scope finding {fid} requires explicit evidence/justification",
                }
        else:
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": f"Finding {fid} has unresolved disposition {disposition!r}",
            }

    if action in ("push_main", "pr_merge"):
        if not human_operator:
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": f"Action {action} requires explicit human publication/merge control (human_operator=True)",
            }
        if action == "pr_merge" and not targets_registered and surface == "forge_workspace":
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": "Workspace PR and Kata targets must be registered before merge",
            }
        return {"allowed": True, "action": action, "surface": surface, "reason": "human operator authorized"}

    if action in ("push_branch", "pr_create", "pr_edit"):
        if branch in ("main", "master"):
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": "Direct branch push/PR from main is blocked; use a task or workspace branch",
            }
        if surface == "private_pi" and not owner_approved:
            return {
                "allowed": False,
                "action": action,
                "surface": surface,
                "reason": f"Action {action} outside a Forge workspace requires explicit owner approval",
            }
        return {"allowed": True, "action": action, "surface": surface, "reason": f"{action} allowed"}

    raise GateError(f"Unknown publication action: {action!r}")


def _write_private_receipt(receipt_path: Path, payload: dict) -> None:
    receipt_path = Path(receipt_path).resolve()
    parent = receipt_path.parent
    if not parent.exists() or not parent.is_dir() or parent.is_symlink():
        raise GateError("Receipt parent directory must exist and be a non-symlink directory")
    parent_mode = stat.S_IMODE(parent.lstat().st_mode)
    if parent_mode & 0o077:
        raise GateError("Receipt parent directory must be private (mode 0700)")
    fd = os.open(receipt_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2)
        handle.write("\n")


def _run_cmd(cwd: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        list(args),
        cwd=str(cwd),
        check=check,
        text=True,
        capture_output=True,
    )


